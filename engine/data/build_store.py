# ---------------------------------------------------------------------------
# 6. SAVE: one SQLite file + CSV copies
# ---------------------------------------------------------------------------
tables = {"depots": depots, "delivery_times": delivery_times, "products": products,
          "inventory": inventory, "policies": policies, "orders": orders}

# We build the database in a temporary folder first, then copy the finished
# file into place. Some shared or synced folders (OneDrive, network drives,
# VM mounts) don't let SQLite lock files while writing; this avoids that.
CSV_DIR.mkdir(exist_ok=True)
tmp_dir = tempfile.mkdtemp()
tmp_db = Path(tmp_dir) / "store.db"
with sqlite3.connect(tmp_db) as con:
    for name, df in tables.items():
        df.to_sql(name, con, index=False)
        df.to_csv(CSV_DIR / f"{name}.csv", index=False)
    # A "view" is a saved question the database can answer like a table.
    con.execute("""
        CREATE VIEW stock_available AS
        SELECT i.sku, i.depot_id, d.depot_name, i.on_hand, i.reserved,
               i.on_hand - i.reserved AS available
        FROM inventory i JOIN depots d USING (depot_id)
    """)

    print(f"Built {DB_PATH.name}")
    for name, df in tables.items():
        print(f"  {name:<15} {len(df):>4} rows")

    # Smoke test: Elena's question, written by hand in SQL.
    elena = pd.read_sql_query("""
        SELECT p.sku, p.name, p.unit_price, s.depot_id, s.available, t.days AS days_to_chicago
        FROM products p
        JOIN stock_available s ON s.sku = p.sku
        JOIN delivery_times t ON t.depot_id = s.depot_id AND t.destination_city = 'Chicago'
        WHERE p.color = 'Navy'
          AND p.material LIKE '%mesh%'
          AND p.armrests = '4D'
          AND p.unit_price <= 350
          AND s.available >= 40
          AND t.days <= 3
        ORDER BY p.unit_price
    """, con)
    print("\nElena's question -> rows that pass every rule:")
    print(elena.to_string(index=False))

con.close()
shutil.copyfile(tmp_db, DB_PATH)
shutil.rmtree(tmp_dir, ignore_errors=True)
print(f"\nSaved -> {DB_PATH}")
