"""Build the fake store database ("the pantry") for CartesianRAG.

WHAT THIS DOES
    Creates store.db, a SQLite database file with 7 tables, plus CSV copies
    you can open in Excel. Run it as many times as you like: it always
    produces exactly the same data (see "seed" below).

    python build_store.py

TWO KINDS OF ROWS
    1. STORY ROWS - written by hand. These are the products from the
       storyboards and wireframes (AeroTask Pro Mesh, ErgoFlex Elite Shell...)
       plus "trap" products that each break ONE of Elena's rules. Because we
       wrote them on purpose, we know the right answer to her question.
    2. FILLER ROWS - generated by a random number generator so the pantry
       feels like a real store (lots of other chairs, desks and accessories).
       Filler is never navy, so it can't accidentally change Elena's answer.

THE SEED
    A random number generator with a fixed "seed" is like shuffling a deck
    of cards the same way every time. seed=42 -> the same "random" products
    on every computer, every run.
"""
